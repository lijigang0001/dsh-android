<#
.SYNOPSIS
    Build and sign the DSH Mobile APK with the Android SDK tools directly.

.DESCRIPTION
    Gradle/AGP cannot finish on this machine: the endpoint security agent
    (Topsec) transparently encrypts every file written by a process whose image
    name is `java.exe`, so AGP's merged-resource `.flat` intermediates come back
    as ciphertext ("magic value is 0x1a031b18 but AAPT expects 0x54504141").
    Verified: `javaw.exe` writes are untouched, `java.exe` writes are not.

    So this script runs the same steps AGP would, while avoiding java.exe:

      aapt2 compile / link        native binaries
      javac                       javac.exe image (unaffected)
      d8                          javaw.exe + d8.jar
      zipalign                    native binary
      apksigner                   javaw.exe + apksigner.jar

.PARAMETER OutDir
    Where to place the signed APK. Defaults to the usual Gradle output path.

.EXAMPLE
    .\build-apk.ps1
#>
[CmdletBinding()]
param(
    [string]$ProjectDir = 'dsh-mobile',
    [string]$OutDir = 'dsh-mobile\app\build\outputs\apk\release',
    [string]$JdkHome = 'D:\Program Files\Java\jdk-19'
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$project = (Resolve-Path (Join-Path $repo $ProjectDir)).Path
$main = Join-Path $project 'app\src\main'
$sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } else { "$env:LOCALAPPDATA\Android\Sdk" }
$buildTools = Get-ChildItem (Join-Path $sdk 'build-tools') -Directory |
    Sort-Object { [version]$_.Name } -Descending | Select-Object -First 1
$platform = Get-ChildItem (Join-Path $sdk 'platforms') -Directory |
    Sort-Object Name -Descending | Select-Object -First 1
$androidJar = Join-Path $platform.FullName 'android.jar'
$bt = $buildTools.FullName
$aapt2 = Join-Path $bt 'aapt2.exe'
$zipalign = Join-Path $bt 'zipalign.exe'
$d8Jar = Join-Path $bt 'lib\d8.jar'
$apksignerJar = Join-Path $bt 'lib\apksigner.jar'
$javac = Join-Path $JdkHome 'bin\javac.exe'
$javaw = Join-Path $JdkHome 'bin\javaw.exe'

foreach ($tool in @($aapt2, $zipalign, $d8Jar, $apksignerJar, $javac, $javaw, $androidJar)) {
    if (-not (Test-Path $tool)) { throw "缺少工具：$tool" }
}

$work = Join-Path $project 'app\build\manual'
if (Test-Path $work) { Remove-Item -Recurse -Force $work }
foreach ($dir in @('res', 'gen', 'classes', 'dex', 'out')) {
    New-Item -ItemType Directory -Force (Join-Path $work $dir) | Out-Null
}
$outDirAbs = Join-Path $repo $OutDir
New-Item -ItemType Directory -Force $outDirAbs | Out-Null

function Step($name) { Write-Host "== $name" -ForegroundColor Yellow }
function RunNative($exe, [string[]]$arguments) {
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) { throw "$exe 失败（exit $LASTEXITCODE）" }
}
# javaw.exe has no console: start it, wait, and surface its exit code.
function RunJavaw($jar, [string[]]$arguments) {
    $all = @('-cp', $jar) + $arguments
    $process = Start-Process -FilePath $javaw -ArgumentList $all -PassThru -Wait -NoNewWindow
    if ($process.ExitCode -ne 0) { throw "javaw $jar 失败（exit $($process.ExitCode)）" }
}

Step 'aapt2 compile'
$resZip = Join-Path $work 'out\res.zip'
RunNative $aapt2 @('compile', '--dir', (Join-Path $main 'res'), '-o', $resZip, '--no-crunch')

Step 'BuildConfig'
$buildConfigDir = Join-Path $work 'gen\com\deepseek\dshmobile'
New-Item -ItemType Directory -Force $buildConfigDir | Out-Null
$buildConfig = @'
package com.deepseek.dshmobile;

/** Generated by tools/build-apk.ps1 — mirrors what AGP would emit. */
public final class BuildConfig {
    public static final boolean DEBUG = false;
    public static final String APPLICATION_ID = "com.deepseek.dshmobile";
    public static final String BUILD_TYPE = "release";
    public static final String VERSION_NAME = "1.0.0";
    public static final int VERSION_CODE = 1;
    private BuildConfig() {
    }
}
'@
[IO.File]::WriteAllText((Join-Path $buildConfigDir 'BuildConfig.java'), $buildConfig, (New-Object System.Text.UTF8Encoding($false)))

Step 'aapt2 link'
# AGP supplies `package` from the module namespace; aapt2 link needs it inside the
# manifest, and AGP 8 refuses a manifest that declares it. So link a copy.
$sourceManifest = Get-Content (Join-Path $main 'AndroidManifest.xml') -Raw -Encoding UTF8
$linkedManifest = Join-Path $work 'AndroidManifest.xml'
$patched = $sourceManifest -replace '<manifest\s+xmlns:android', '<manifest package="com.deepseek.dshmobile" xmlns:android'
if ($patched -eq $sourceManifest) { throw '无法在清单里注入 package 属性' }
[IO.File]::WriteAllText($linkedManifest, $patched, (New-Object System.Text.UTF8Encoding($false)))
$baseApk = Join-Path $work 'out\base.apk'
RunNative $aapt2 @(
    'link', '-o', $baseApk,
    '-I', $androidJar,
    '--manifest', $linkedManifest,
    '-A', (Join-Path $main 'assets'),
    '--java', (Join-Path $work 'gen'),
    '--min-sdk-version', '24',
    '--target-sdk-version', '34',
    '--version-code', '1',
    '--version-name', '1.0.0',
    $resZip
)

Step 'javac'
$sources = @()
$sources += Get-ChildItem (Join-Path $main 'java') -Recurse -Filter '*.java' | Select-Object -ExpandProperty FullName
$sources += Get-ChildItem (Join-Path $work 'gen') -Recurse -Filter '*.java' | Select-Object -ExpandProperty FullName
$classesDir = Join-Path $work 'classes'
$javacArgs = @(
    '-encoding', 'UTF-8',
    '-source', '17', '-target', '17',
    '-Xlint:-options',
    '-classpath', $androidJar,
    '-d', $classesDir
) + $sources
RunNative $javac $javacArgs

Step 'd8'
$classFiles = Get-ChildItem $classesDir -Recurse -Filter '*.class' | Select-Object -ExpandProperty FullName
$dexDir = Join-Path $work 'dex'
RunJavaw $d8Jar (@('com.android.tools.r8.D8', '--release', '--min-api', '24', '--lib', $androidJar,
    '--output', $dexDir) + $classFiles)
$dex = Join-Path $dexDir 'classes.dex'
$dexMagic = [Text.Encoding]::ASCII.GetString(([IO.File]::ReadAllBytes($dex))[0..6])
# d8 emits a level-specific header: dex\n035 (API 24 baseline) up to dex\n039.
if ($dexMagic -notmatch '^dex\n03[5-9]$') {
    throw "classes.dex 头不对（$dexMagic），说明写出被安全代理加密了"
}

Step 'package'
$unsigned = Join-Path $work 'out\unsigned.apk'
Copy-Item $baseApk $unsigned -Force
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [System.IO.Compression.ZipFile]::Open($unsigned, 'Update')
try {
    $existing = $zip.GetEntry('classes.dex')
    if ($existing) { $existing.Delete() }
    $entry = $zip.CreateEntry('classes.dex', [System.IO.Compression.CompressionLevel]::Optimal)
    $stream = $entry.Open()
    $bytes = [IO.File]::ReadAllBytes($dex)
    $stream.Write($bytes, 0, $bytes.Length)
    $stream.Dispose()
} finally {
    $zip.Dispose()
}

Step 'zipalign'
$aligned = Join-Path $work 'out\aligned.apk'
RunNative $zipalign @('-f', '-p', '4', $unsigned, $aligned)

Step 'apksigner'
$keystore = Join-Path $project 'app\keystore\dsh-mobile.jks'
if (-not (Test-Path $keystore)) { throw "找不到签名库：$keystore" }
$signed = Join-Path $outDirAbs 'app-release.apk'
RunJavaw $apksignerJar @(
    'com.android.apksigner.ApkSignerTool', 'sign',
    '--ks', $keystore,
    '--ks-key-alias', 'dsh-mobile',
    '--ks-pass', 'pass:dshmobile',
    '--key-pass', 'pass:dshmobile',
    '--v1-signing-enabled', 'true',
    '--v2-signing-enabled', 'true',
    '--min-sdk-version', '24',
    '--out', $signed,
    $aligned
)

Step 'done'
$info = Get-Item $signed
Write-Host ("APK   : {0}" -f $info.FullName) -ForegroundColor Green
Write-Host ("Size  : {0:N1} KB" -f ($info.Length / 1KB)) -ForegroundColor Green
Write-Host ("SHA256: {0}" -f (Get-FileHash $signed -Algorithm SHA256).Hash) -ForegroundColor DarkGray
